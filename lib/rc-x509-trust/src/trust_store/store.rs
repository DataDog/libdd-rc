use bytes::Bytes;
use rc_crypto::{Signature, certificate::id::CertId, keys::SignatureVerifyErr};
use rc_x509_roots::RootCertificate;
use thiserror::Error;
use tracing::{debug, error, trace};
use valuable::Valuable;

use crate::{
    EndpointHostname,
    cert::UntrustedCert,
    chain::{
        ChainBuildError, ChainVerifyError, EKUPolicy, build_unverified_chain_for, verify_chain,
    },
    trust_store::{CertCache, RootSet},
};

/// Errors during signature verification.
#[derive(Debug, Error)]
pub enum VerificationError {
    /// A certificate identified as the signing certificate is not in the local
    /// cache.
    #[error("no local leaf certificate for cert ID: {0}")]
    MissingLeafCert(CertId),

    /// Building a chain to a known root has failed (notably including: missing
    /// intermediate in the local cache).
    #[error("chain building error: {0}")]
    ChainBuild(#[from] ChainBuildError),

    /// The candidate chain cannot be trusted and the payload should be
    /// discarded.
    #[error("chain verify error: {0}")]
    ChainVerify(#[from] ChainVerifyError),

    /// The chain was valid and trusted, but the signature did not originate
    /// from the indicated leaf / signer certificate.
    #[error("signature verify error: {0}")]
    Signature(#[from] SignatureVerifyErr),
}

/// A [`TrustStore`] provides payload signature verification using a cache of
/// known, but untrusted, local X509 certificates.
#[derive(Debug)]
pub struct TrustStore<const N: usize, T> {
    roots: RootSet<N>,

    /// A cache of known (untrusted) certificates.
    cache: T,
}

impl<const N: usize, T> TrustStore<N, T>
where
    T: CertCache,
{
    /// Initialise a [`TrustStore`] to verify any payload signature chains to
    /// `root`, using certificates in `cache`.
    pub fn new(roots: [RootCertificate; N], cache: T) -> Self {
        Self {
            roots: RootSet::new(roots),
            cache,
        }
    }

    /// Perform a batch insertion of all the provided (untrusted) certificates
    /// to the certificate cache.
    ///
    /// Calling this method requires locking the cache.
    pub fn add<U>(&self, certs: U)
    where
        U: Iterator<Item = UntrustedCert>,
    {
        for cert in certs {
            debug!(
                cert = cert.as_value(),
                "adding new certificate to local cache"
            );

            self.cache.insert(cert);
        }
    }

    /// Verify that `signature` was generated by `signing_cert_id` for
    /// `payload`, and that it chains to a known root, returning an error if
    /// this cannot be proven.
    ///
    /// Asserts the signer certificate is allowed to sign payloads for the DC
    /// hostname specified in `endpoint`.
    ///
    /// # Logging
    ///
    /// This method only logs at DEBUG, it is the callers responsibility to log
    /// success / failure.
    pub fn verify(
        &self,
        signing_cert_id: CertId,
        signature: Signature,
        payload: Bytes,
        endpoint: &EndpointHostname,
    ) -> Result<(), VerificationError> {
        let leaf = self
            .cache
            .get(&signing_cert_id)
            .ok_or_else(|| VerificationError::MissingLeafCert(signing_cert_id))?;

        // Build a candidate chain, that may be completely untrustworthy.
        //
        // Because the X509 platform has an design security invariant of "no
        // keys have their validity extended" / "no keys are reused", there is
        // only ever one chain to a given leaf certificate to consider, because
        // signatures are generated by keys - therefore a single key has a
        // single cert, which has a single issuer keypair + cert, and so on to
        // the root, thus a single chain.
        let candidate_chain = build_unverified_chain_for(&self.roots, &leaf, &self.cache)?;

        trace!(
            %endpoint,
            candidate_chain = candidate_chain.as_value(),
            "unverified chain built for signature verification"
        );

        // Verify the chain is valid - see `verify_chain()` for the specifics.
        let cert = match verify_chain(
            &leaf,
            candidate_chain,
            EKUPolicy::RequireCodeSigning,
            endpoint,
        ) {
            Ok(cert) => {
                // Success - the chain is valid and trusted for use in this
                // function call only, continue to signature checks.

                debug!(
                    %signature,
                    %endpoint,
                    signer_cert = cert.as_value(),
                    "chain verified as trusted"
                );

                cert
            }
            Err(e) => {
                // The chain is invalid, and not because of a missing
                // certificate.

                debug!(
                    error=%e,
                    %signature,
                    %endpoint,
                    signer_cert = leaf.as_value(),
                    "chain verification failed"
                );

                return Err(VerificationError::ChainVerify(e));
            }
        };

        // Finally, verify the signature against the known-valid chain, which
        // may or may not have produced the signature.
        match cert.public_key().verify(&payload, &signature) {
            Ok(()) => {
                // Success - this signature is valid.

                debug!(
                    %signature,
                    %endpoint,
                    signer_cert = cert.as_value(),
                    "signature verified"
                );

                Ok(())
            }
            Err(e) => {
                // This signature was not produced by the `signing_cert_id`.

                error!(
                    error=%e,
                    %signature,
                    %endpoint,
                    signer_cert = leaf.as_value(),
                    "signature verification failure"
                );

                Err(VerificationError::Signature(e))
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use std::iter;

    use assert_matches::assert_matches;
    use proptest::prelude::*;

    use crate::{
        chain::tests::{ChainError, InvalidChain, arbitrary_invalid_chain},
        test_issuer::{MissingIntermediate, TestCA, TestChain, ValidChain, arbitrary_chain},
        trust_store::{cache::MemoryCertCache, tests::arbitrary_ordered_root_set},
    };

    use super::*;

    static CA: TestCA = TestCA::new();
    static CA2: TestCA = TestCA::new();

    /// The SAN of the leaf certificate in a [`TestChain`].
    const DEFAULT_LEAF_SAN: &str = "leaf.itsallbroken.com";

    proptest! {
        /// Generate a random, valid chain with 0 to 5 intermediates between the
        /// root and the leaf and ensure it can be used to verify a payload.
        #[test]
        fn prop_verify(
            roots in arbitrary_ordered_root_set(&CA, &CA2),
            input in arbitrary_chain(&CA, 0..=5_u8, ValidChain::default()),
            data in crate::tests::arbitrary_bytes(0..1025),
        ) {
            test_prop_verify(roots, input, data);
        }

        /// Process a chain that is missing a random certificate in the local
        /// cache, which must be correctly identified in the returned error.
        ///
        /// An intermediate is always missing, but if `drop_leaf` is true, then
        /// a leaf is also left out from the local cache, and the error is
        /// expected to identify the leaf as the missing certificate.
        #[test]
        fn prop_missing_local_certificate(
            roots in arbitrary_ordered_root_set(&CA, &CA2),
            rnd in any::<u8>(),
            (input, mutator) in (1..=5_u8, any::<u8>())
                .prop_map(|(n, seed)| {
                    let mutator = MissingIntermediate::new(seed);
                    (TestChain::build(&CA, n, &mutator), mutator)
            }),
        ) {
            // 1-in-10 chance of dropping the leaf, all other runs drop a
            // randomly selected intermediate.
            let drop_leaf = rnd % 10 == 0;

            test_prop_missing_local_certificate(roots, input, mutator, drop_leaf);
        }

        /// Generate an invalid chain, by applying a random ChainMutator, each
        /// of which manipulates the chain to produce an invalid input chain.
        #[test]
        fn prop_invalid_chain(
            roots in arbitrary_ordered_root_set(&CA, &CA2),
            input in arbitrary_invalid_chain(&CA, 2..=5_u8),
        ) {
            test_prop_invalid_chain(roots, input);
        }

        /// Assert a valid chain paired with an invalid signature causes an
        /// error to be returned.
        #[test]
        fn prop_bad_signature(
            roots in arbitrary_ordered_root_set(&CA, &CA2),
            input in arbitrary_chain(&CA, 0..=5_u8, ValidChain::default()),
            data in crate::tests::arbitrary_bytes(0..1025),
            sig in crate::tests::arbitrary_bytes(1..=120),
        ) {
            let sig = Signature::try_from(&*sig).unwrap();
            test_prop_bad_signature(roots, input, data, sig);
        }

        /// Assert a payload signed by a different leaf is not accepted when
        /// claiming it is from another cert.
        #[test]
        fn prop_valid_mismatched_signature(
            roots in arbitrary_ordered_root_set(&CA, &CA2),
            chain in arbitrary_chain(&CA, 0..=5_u8, ValidChain::default()),
            unrelated_chain in arbitrary_chain(&CA, 0..=5_u8, ValidChain::default()),
            data in crate::tests::arbitrary_bytes(0..1025),
        ) {
            // Sign the payload using "unrelated_chain", which produces a valid
            // signature, just not from the leaf we're going to claim is the
            // signer.
            let sig = unrelated_chain.leaf.sign(&data);
            drop(unrelated_chain);

            test_prop_bad_signature(roots, chain, data, sig);
        }
    }

    fn test_prop_verify(roots: RootSet<2>, chain: TestChain, data: Bytes) {
        let cache = MemoryCertCache::new(1024 * 1024);
        let store = TrustStore::new(roots.into_array(), cache);

        // Populate the trust store with all the intermediates & leaf
        // certificate.
        store.add(
            chain
                .intermediates
                .iter()
                .chain(iter::once(&chain.leaf))
                .map(|v| UntrustedCert::from(v.cert().clone())),
        );

        // Generate a valid signature for the random payload data.
        let signature = chain.leaf.sign(&data);

        // verify!
        store
            .verify(
                chain.leaf.cert().cert_id().clone(),
                signature,
                data,
                &EndpointHostname::try_from(DEFAULT_LEAF_SAN.to_owned()).unwrap(),
            )
            .expect("valid chain")
    }

    fn test_prop_invalid_chain(roots: RootSet<2>, chain: InvalidChain) {
        let cache = MemoryCertCache::new(1024 * 1024);
        let store = TrustStore::new(roots.into_array(), cache);

        // Populate the trust store with all the intermediates & leaf
        // certificate.
        store.add(
            chain
                .intermediates
                .iter()
                .chain(iter::once(&chain.leaf))
                .map(|v| UntrustedCert::from(v.cert().clone())),
        );

        // verify!
        let err = store
            .verify(
                chain.leaf.cert().cert_id().clone(),
                Signature::try_from(&[42_u8][..]).expect("well formed"),
                Default::default(),
                &EndpointHostname::try_from(DEFAULT_LEAF_SAN.to_owned()).unwrap(),
            )
            .expect_err("invalid chain");

        // Assert the expected error for this invalid chain mutator was returned
        // in the wrapped store error.
        chain.assert_err(match err {
            VerificationError::MissingLeafCert(_) => unreachable!(),
            VerificationError::ChainBuild(e) => ChainError::Build(e),
            VerificationError::ChainVerify(e) => ChainError::Verify(e),
            VerificationError::Signature(_) => unreachable!(), // Fails before this
        });
    }

    fn test_prop_missing_local_certificate(
        roots: RootSet<2>,
        chain: TestChain,
        mutator: MissingIntermediate,
        drop_leaf: bool,
    ) {
        let cache = MemoryCertCache::new(1024 * 1024);
        let store = TrustStore::new(roots.into_array(), cache);

        // Maybe include the leaf in the iterator that adds to the local cache.
        let maybe_leaf: Box<dyn Iterator<Item = _>> = match drop_leaf {
            true => Box::from(iter::empty()),
            false => Box::from(iter::once(&chain.leaf)),
        };

        // Populate the trust store with all the intermediates & leaf
        // certificate, if included.
        store.add(
            chain
                .intermediates
                .iter()
                .chain(maybe_leaf)
                .map(|v| UntrustedCert::from(v.cert().clone())),
        );

        // verify!
        let err = store
            .verify(
                chain.leaf.cert().cert_id().clone(),
                Signature::try_from(&[42_u8][..]).expect("well formed"),
                Default::default(),
                &EndpointHostname::try_from(DEFAULT_LEAF_SAN.to_owned()).unwrap(),
            )
            .expect_err("has missing cert");

        // Extract the cert ID from the error and the expected value - this
        // value is used to query the backend for the missing cert.
        let (want, got) = match drop_leaf {
            true => {
                let want = chain.leaf.cert().cert_id().clone();
                let got = assert_matches!(
                    err,
                    VerificationError::MissingLeafCert(id) => id
                );

                (want, got)
            }
            false => {
                let want = mutator.take_dropped().unwrap().cert().cert_id().clone();

                let got = assert_matches!(
                    err,
                    VerificationError::ChainBuild(ChainBuildError::MissingIntermediate(id)) => id
                );

                (want, got.as_cert_id().clone())
            }
        };

        // It must match the missing certificate's identifier.
        assert_eq!(
            want.as_dangerous_comparable(),
            got.as_dangerous_comparable()
        );
    }

    fn test_prop_bad_signature(roots: RootSet<2>, chain: TestChain, data: Bytes, sig: Signature) {
        let cache = MemoryCertCache::new(1024 * 1024);
        let store = TrustStore::new(roots.into_array(), cache);

        // Populate the trust store with all the intermediates & leaf
        // certificate.
        store.add(
            chain
                .intermediates
                .iter()
                .chain(iter::once(&chain.leaf))
                .map(|v| UntrustedCert::from(v.cert().clone())),
        );

        // verify!
        let err = store
            .verify(
                chain.leaf.cert().cert_id().clone(),
                sig,
                data,
                &EndpointHostname::try_from(DEFAULT_LEAF_SAN.to_owned()).unwrap(),
            )
            .expect_err("invalid signature");

        assert_matches!(err, VerificationError::Signature(SignatureVerifyErr));
    }
}
