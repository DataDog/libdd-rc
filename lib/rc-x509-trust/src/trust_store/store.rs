use bytes::Bytes;
use rc_crypto::{Signature, certificate::id::CertId};
use rc_x509_roots::RootCertificate;
use thiserror::Error;
use tracing::{info, trace};
use valuable::Valuable;

use crate::{
    cert::UntrustedCert,
    chain::{ChainBuildError, build_unverified_chain_for},
    trust_store::CertCache,
};

/// Errors during signature verification.
#[derive(Debug, Error)]
pub enum VerificationError {
    /// A certificate identified as the signing certificate is not in the local
    /// cache.
    #[error("no local leaf certificate for cert ID: {0}")]
    MissingLeafCert(CertId),

    /// Building a chain to a known root has failed (notably including: missing
    /// intermediate in the local cache).
    #[error("chain building error: {0}")]
    ChainBuild(#[from] ChainBuildError),
}

/// A [`TrustStore`] provides payload signature verification using a cache of
/// known, but untrusted, local X509 certificates.
#[derive(Debug)]
pub struct TrustStore<T> {
    root: RootCertificate,

    /// A cache of known (untrusted) certificates.
    cache: T,
}

impl<T> TrustStore<T>
where
    T: CertCache,
{
    /// Initialise a [`TrustStore`] to verify any payload signature chains to
    /// `root`, using certificates in `cache`.
    pub fn new(root: RootCertificate, cache: T) -> Self {
        Self { root, cache }
    }

    /// Add a new (untrusted) certificate to the certificate cache.
    pub fn add(&mut self, cert: UntrustedCert) {
        info!(
            cert = cert.as_value(),
            "adding new certificate to local cache"
        );
        self.cache.insert(cert);
    }

    /// Verify that `signature` was generated by `signing_cert_id` for
    /// `payload`, and that it chains to a known root, returning an error if
    /// this cannot be proven.
    pub fn validate(
        &self,
        signing_cert_id: CertId,
        _signature: Signature,
        _payload: Bytes,
    ) -> Result<(), VerificationError> {
        let cert = self
            .cache
            .get(&signing_cert_id)
            .ok_or_else(|| VerificationError::MissingLeafCert(signing_cert_id))?;

        // Build a candidate chain, that may be completely untrustworthy.
        //
        // Because the X509 platform has an design security invariant of "no
        // keys have their validity extended" / "no keys are reused", there is
        // only ever one chain to a given leaf certificate to consider, because
        // signatures are generated by keys - therefore a single key has a
        // single cert, which has a single issuer keypair + cert, and so on to
        // the root, thus a single chain.
        let candidate_chain = build_unverified_chain_for(&self.root, &cert, &self.cache)?;

        trace!(
            candidate_chain = candidate_chain.as_value(),
            "unverified chain built for signature verification"
        );

        // TODO(dom): verify chain + signature

        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use std::iter;

    use assert_matches::assert_matches;
    use proptest::prelude::*;

    use crate::{
        test_issuer::{MissingIntermediate, TestCA, TestChain, ValidChain, arbitrary_chain},
        trust_store::cache::MemoryCertCache,
    };

    use super::*;

    static CA: TestCA = TestCA::new();

    proptest! {
        /// Generate a random, valid chain with 0 to 5 intermediates between the
        /// root and the leaf and ensure it can be used to validate a payload.
        #[test]
        fn prop_validate(
            input in arbitrary_chain(&CA, 0..=5_u8, ValidChain::default()),
        ) {
            test_prop_validate(input);
        }

        /// Ensure that a missing intermediate causes a validation failure and
        /// is correctly identified in the return value.
        #[test]
        fn prop_missing_local_certificate(
            rnd in any::<u8>(),
            (input, mutator) in (1..=5_u8, any::<u8>())
                .prop_map(|(n, seed)| {
                    let mutator = MissingIntermediate::new(seed);
                    (TestChain::build(&CA, n, &mutator), mutator)
            }),
        ) {
            // 1-in-10 chance of dropping the leaf, all other runs drop a
            // randomly selected intermediate.
            let drop_leaf = rnd % 10 == 0;

            test_prop_missing_local_certificate(input, mutator, drop_leaf);
        }
    }

    /// Process a valid chain, expecting success.
    fn test_prop_validate(chain: TestChain) {
        let cache = MemoryCertCache::default();
        let mut store = TrustStore::new(chain.root(), cache);

        // Populate the trust store with all the intermediates & leaf
        // certificate.
        for cert in chain.intermediates.iter().chain(iter::once(&chain.leaf)) {
            store.add(UntrustedCert::from(cert.cert().clone()));
        }

        // Validate!
        store
            .validate(
                chain.leaf.cert().cert_id().clone(),
                Signature::try_from(&[42_u8][..]).expect("well formed"),
                Default::default(),
            )
            .expect("valid chain")
    }

    /// Process a chain that is missing a random certificate in the local cache,
    /// which must be correctly identified in the returned error.
    ///
    /// An intermediate is always missing, but if `drop_leaf` is true, then a
    /// leaf is also left out from the local cache, and the error is expected to
    /// identify the leaf as the missing certificate.
    fn test_prop_missing_local_certificate(
        chain: TestChain,
        mutator: MissingIntermediate,
        drop_leaf: bool,
    ) {
        let cache = MemoryCertCache::default();
        let mut store = TrustStore::new(chain.root(), cache);

        // Maybe include the leaf in the iterator that adds to the local cache.
        let maybe_leaf: Box<dyn Iterator<Item = _>> = match drop_leaf {
            true => Box::from(iter::empty()),
            false => Box::from(iter::once(&chain.leaf)),
        };

        // Populate the trust store with all the intermediates & leaf
        // certificate, if included.
        for cert in chain.intermediates.iter().chain(maybe_leaf) {
            store.add(UntrustedCert::from(cert.cert().clone()));
        }

        // Validate!
        let err = store
            .validate(
                chain.leaf.cert().cert_id().clone(),
                Signature::try_from(&[42_u8][..]).expect("well formed"),
                Default::default(),
            )
            .expect_err("has missing cert");

        // Extract the cert ID from the error and the expected value - this
        // value is used to query the backend for the missing cert.
        let (want, got) = match drop_leaf {
            true => {
                let want = chain.leaf.cert().cert_id().clone();
                let got = assert_matches!(
                    err,
                    VerificationError::MissingLeafCert(id) => id
                );

                (want, got)
            }
            false => {
                let want = mutator.take_dropped().unwrap().cert().cert_id().clone();

                let got = assert_matches!(
                    err,
                    VerificationError::ChainBuild(ChainBuildError::MissingIntermediate(id)) => id
                );

                (want, got.as_cert_id().clone())
            }
        };

        // It must match the missing certificate's identifier.
        assert_eq!(
            want.as_dangerous_comparable(),
            got.as_dangerous_comparable()
        );
    }
}
