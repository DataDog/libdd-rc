//! Internal trust chain building, and chain validation logic.
#![allow(clippy::module_inception)]

mod build_unverified;
mod unverified;
mod verify_chain;

pub use build_unverified::*;
pub(crate) use unverified::*;

#[allow(dead_code, unused_imports)]
pub(crate) use verify_chain::*;

/// These property test input generator functions are used to classify attacks
/// and document at which stage they fail during processing. Either:
///
///   * Chain building (using SKI / AKI values).
///   * Chain verification (using cryptographic signatures and constrain
///     checks).
///
#[cfg(test)]
pub(crate) mod tests {
    use std::{fmt::Debug, ops::Deref, sync::Arc};

    use assert_matches::assert_matches;
    use proptest::prelude::*;

    use crate::{
        chain::{ChainBuildError, ChainVerifyError},
        test_issuer::{
            CaSignerLeaf, CriticalExtensionIntermediate, CriticalExtensionLeaf,
            ExpiredIntermediate, ExpiredLeaf, ForgedIntermediate, ForgedLeaf,
            FutureValidIntermediate, FutureValidLeaf, MismatchedLeafSan, MissingIntermediate,
            NonCaIntermediate, OrphanLeaf, PathLenViolation, PreEpochIntermediate, PreEpochLeaf,
            SelfReferentialCertIds, TestCA, TestChain, arbitrary_chain,
        },
    };

    /// The error observed when processing an [`InvalidChain`], identifying
    /// which of the two chain processing stages rejected it.
    #[derive(Debug)]
    pub(crate) enum ChainError {
        /// The chain was rejected during chain building, using SKI / AKI
        /// values.
        Build(ChainBuildError),

        /// The chain was successfully built, and rejected during chain
        /// verification.
        Verify(ChainVerifyError),
    }

    /// An assertion over the [`ChainError`] processing an [`InvalidChain`] MUST
    /// produce.
    type ErrorAssertion = Arc<dyn Fn(&ChainError) + Send + Sync>;

    /// A [`TestChain`] that has had a mutation applied which renders it
    /// invalid, carrying an assertion that describes precisely how processing
    /// it MUST fail.
    ///
    /// Each generator arm pairs the mutation it applies with the error that
    /// mutation causes, so a single property test covers every mutation without
    /// losing the precision of asserting the specific error each one produces.
    /// Without it, a test can only assert that processing failed, which a chain
    /// rejected for an entirely unrelated reason also satisfies.
    pub(crate) struct InvalidChain {
        /// A description of the applied mutation, included in the [`Debug`]
        /// output proptest prints for a failing input.
        mutation: &'static str,

        /// The mutated chain.
        chain: TestChain,

        /// The assertion applied to the error observed when processing
        /// [`Self::chain`].
        assert_err: ErrorAssertion,
    }

    impl Debug for InvalidChain {
        fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
            f.debug_struct("InvalidChain")
                .field("mutation", &self.mutation)
                .field("chain", &self.chain)
                .finish_non_exhaustive()
        }
    }

    impl Deref for InvalidChain {
        type Target = TestChain;

        fn deref(&self) -> &Self::Target {
            &self.chain
        }
    }

    impl InvalidChain {
        /// Pair the mutated chains generated by `chain` with the
        /// [`ChainError`] assertion every one of them MUST satisfy.
        ///
        /// `mutation` names the mutation `chain` applies, and appears in the
        /// [`Debug`] output for a failing input.
        fn new<S, F>(mutation: &'static str, chain: S, assert_err: F) -> impl Strategy<Value = Self>
        where
            S: Strategy<Value = TestChain>,
            F: Fn(&ChainError) + Clone + Send + Sync + 'static,
        {
            chain.prop_map(move |chain| Self {
                mutation,
                chain,
                assert_err: Arc::new(assert_err.clone()),
            })
        }

        /// Assert `got` is the error the mutation applied to this chain MUST
        /// produce.
        pub(crate) fn assert_err(&self, got: ChainError) {
            (self.assert_err)(&got)
        }
    }

    /// Generate `n_intermediates` and a random mutator seed, for mutators that
    /// select which certificate in the chain to target.
    fn arbitrary_seeded_chain(
        ca: &'static TestCA,
        n_intermediates: impl Strategy<Value = u8> + 'static,
        build: fn(&'static TestCA, u8, u8) -> TestChain,
    ) -> impl Strategy<Value = TestChain> {
        n_intermediates
            .prop_flat_map(|n| any::<u8>().prop_map(move |seed| (n, seed)))
            .prop_map(move |(n, seed)| build(ca, n, seed))
    }

    /// A set of chain mutations that result in an invalid chain being produced,
    /// which is not detected as invalid by [`build_unverified_chain_for()`] and
    /// returned to the caller (needing further verification).
    ///
    /// [`build_unverified_chain_for()`]: super::build_unverified_chain_for
    pub(crate) fn arbitrary_invalid_chain_spuriously_built(
        ca: &'static TestCA,
        n_intermediates: impl Strategy<Value = u8> + Clone + 'static,
    ) -> impl Strategy<Value = InvalidChain> {
        prop_oneof![
            InvalidChain::new(
                "ForgedLeaf",
                arbitrary_chain(ca, n_intermediates.clone(), ForgedLeaf::default()),
                |got| assert_matches!(
                    got,
                    ChainError::Verify(ChainVerifyError::CertSignatureInvalid)
                ),
            ),
            InvalidChain::new(
                "PathLenViolation",
                arbitrary_chain(ca, n_intermediates.clone(), PathLenViolation::default()),
                |got| assert_matches!(got, ChainError::Verify(ChainVerifyError::PathLen)),
            ),
            InvalidChain::new(
                "ExpiredLeaf",
                arbitrary_chain(ca, n_intermediates.clone(), ExpiredLeaf::default()),
                |got| assert_matches!(
                    got,
                    ChainError::Verify(ChainVerifyError::CertExpired { .. })
                ),
            ),
            InvalidChain::new(
                "FutureValidLeaf",
                arbitrary_chain(ca, n_intermediates.clone(), FutureValidLeaf::default()),
                |got| assert_matches!(
                    got,
                    ChainError::Verify(ChainVerifyError::CertFutureValidity { .. })
                ),
            ),
            InvalidChain::new(
                "ForgedIntermediate",
                arbitrary_seeded_chain(ca, n_intermediates.clone(), |ca, n, seed| {
                    TestChain::build(ca, n, &ForgedIntermediate::new(seed))
                }),
                |got| assert_matches!(
                    got,
                    ChainError::Verify(ChainVerifyError::CertSignatureInvalid)
                ),
            ),
            InvalidChain::new(
                "ExpiredIntermediate",
                arbitrary_seeded_chain(ca, n_intermediates.clone(), |ca, n, seed| {
                    TestChain::build(ca, n, &ExpiredIntermediate::new(seed))
                }),
                |got| assert_matches!(
                    got,
                    ChainError::Verify(ChainVerifyError::CertExpired { .. })
                ),
            ),
            InvalidChain::new(
                "FutureValidIntermediate",
                arbitrary_seeded_chain(ca, n_intermediates.clone(), |ca, n, seed| {
                    TestChain::build(ca, n, &FutureValidIntermediate::new(seed))
                }),
                |got| assert_matches!(
                    got,
                    ChainError::Verify(ChainVerifyError::CertFutureValidity { .. })
                ),
            ),
            InvalidChain::new(
                "CaSignerLeaf",
                arbitrary_chain(ca, n_intermediates.clone(), CaSignerLeaf::default()),
                |got| assert_matches!(got, ChainError::Verify(ChainVerifyError::SignerIsCa)),
            ),
            InvalidChain::new(
                "MismatchedLeafSan",
                arbitrary_chain(ca, n_intermediates.clone(), MismatchedLeafSan::default()),
                |got| assert_matches!(
                    got,
                    ChainError::Verify(ChainVerifyError::LeafNameMismatch { .. })
                ),
            ),
            InvalidChain::new(
                "PreEpochLeaf",
                arbitrary_chain(ca, n_intermediates.clone(), PreEpochLeaf::default()),
                |got| assert_matches!(
                    got,
                    ChainError::Verify(ChainVerifyError::CertMalformed(webpki::Error::BadDerTime))
                ),
            ),
            InvalidChain::new(
                "CriticalExtensionLeaf",
                arbitrary_chain(
                    ca,
                    n_intermediates.clone(),
                    CriticalExtensionLeaf::default()
                ),
                |got| assert_matches!(
                    got,
                    ChainError::Verify(ChainVerifyError::Unsupported(
                        webpki::Error::UnsupportedCriticalExtension
                    ))
                ),
            ),
            InvalidChain::new(
                "OrphanLeaf",
                arbitrary_chain(ca, n_intermediates.clone(), OrphanLeaf::default()),
                |got| assert_matches!(
                    got,
                    ChainError::Verify(ChainVerifyError::ChainBuildingMismatch)
                ),
            ),
            InvalidChain::new(
                "NonCaIntermediate",
                arbitrary_seeded_chain(ca, n_intermediates.clone(), |ca, n, seed| {
                    TestChain::build(ca, n, &NonCaIntermediate::new(seed))
                }),
                |got| assert_matches!(got, ChainError::Verify(ChainVerifyError::IntermediateNotCa)),
            ),
            InvalidChain::new(
                "PreEpochIntermediate",
                arbitrary_seeded_chain(ca, n_intermediates.clone(), |ca, n, seed| {
                    TestChain::build(ca, n, &PreEpochIntermediate::new(seed))
                }),
                |got| assert_matches!(
                    got,
                    ChainError::Verify(ChainVerifyError::CertMalformed(webpki::Error::BadDerTime))
                ),
            ),
            InvalidChain::new(
                "CriticalExtensionIntermediate",
                arbitrary_seeded_chain(ca, n_intermediates, |ca, n, seed| {
                    TestChain::build(ca, n, &CriticalExtensionIntermediate::new(seed))
                }),
                |got| assert_matches!(
                    got,
                    ChainError::Verify(ChainVerifyError::Unsupported(
                        webpki::Error::UnsupportedCriticalExtension
                    ))
                ),
            ),
        ]
    }

    /// The set of chain mutations which MUST be detected as resulting in an
    /// invalid chain at some point during chain processing.
    ///
    /// This set covers all mutations that result in an invalid chain, and is a
    /// strict superset of [`arbitrary_invalid_chain_spuriously_built()`].
    pub(crate) fn arbitrary_invalid_chain(
        ca: &'static TestCA,
        n_intermediates: impl Strategy<Value = u8> + Clone + 'static,
    ) -> impl Strategy<Value = InvalidChain> {
        prop_oneof![
            // All the inputs that result in an UntrustedChain being constructed
            // from an invalid input chain.
            arbitrary_invalid_chain_spuriously_built(ca, n_intermediates.clone()),
            // Plus test cases that are not spuriously accepted during chain
            // building, but MUST be rejected either during chain building or
            // verification.
            InvalidChain::new(
                "SelfReferentialCertIds",
                arbitrary_chain(
                    ca,
                    n_intermediates.clone(),
                    SelfReferentialCertIds::default()
                ),
                // The AKI -> SKI cycle means the walk never reaches a root, so
                // it is the chain length bound that terminates it.
                |got| assert_matches!(
                    got,
                    ChainError::Build(ChainBuildError::ExcessivelyLongChain)
                ),
            ),
            InvalidChain::new(
                "MissingIntermediate",
                arbitrary_seeded_chain(ca, n_intermediates, |ca, n, seed| {
                    TestChain::build(ca, n, &MissingIntermediate::new(seed))
                }),
                |got| assert_matches!(
                    got,
                    ChainError::Build(ChainBuildError::MissingIntermediate(..))
                ),
            ),
        ]
    }
}
